from pydantic import BaseModel, Field
from typing import List, Optional


class SongSearchRequest(BaseModel):
    query: str = Field(min_length=1, max_length=500)
    artist: Optional[str] = None


class RecommendationRequest(BaseModel):
    liked_songs: List[str] = Field(max_length=50)
    target_artist: Optional[str] = None
    num_recommendations: int = Field(default=10, ge=1, le=50)
    mood: Optional[str] = None


class MoodRequest(BaseModel):
    mood: str
    era: Optional[str] = None
    limit: int = Field(default=20, ge=1, le=50)


class CrossArtistRequest(BaseModel):
    song_id: str
    limit: int = Field(default=10, ge=1, le=50)


class CompareRequest(BaseModel):
    liked_songs: List[str] = Field(max_length=50)  # Spotify track IDs
    song_names: List[str] = Field(default_factory=list, max_length=50)  # Taylor song names for editorial lookup
    num_per_engine: int = Field(default=6, ge=1, le=50)


class EraRequest(BaseModel):
    era: str


class PlaylistRequest(BaseModel):
    songs: List[str] = Field(min_length=1, max_length=100)
    name: str = Field(default="Shubz-Taylor Recommendations", min_length=1, max_length=100)
    description: str = Field(default="Generated by The Shubz-Taylor Recommendation Engine", max_length=300)
